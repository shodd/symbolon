//! Typed identifiers (PROTOCOL.md §0).
//!
//! Every ID is a UUIDv4 (version 4, RFC 9562 variant). The only exception is
//! the nil item ID, [`ItemId::VAULT_META`]. In JSON an ID is the lowercase
//! canonical string (`xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx`); in CBOR it is the
//! 16-byte form (`to_bytes` / `from_bytes`). Parsing is strict: uppercase,
//! braces, URN prefixes, un-hyphenated forms and other UUID versions are
//! rejected, so one ID has exactly one spelling.

use core::fmt;
use core::str::FromStr;

use serde::de::{self, Visitor};
use serde::{Deserialize, Deserializer, Serialize, Serializer};
use uuid::Uuid;

/// The input was not a lowercase canonical UUIDv4.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct IdParseError;

impl fmt::Display for IdParseError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("expected a lowercase canonical UUIDv4")
    }
}

impl core::error::Error for IdParseError {}

fn parse_canonical(s: &str) -> Result<Uuid, IdParseError> {
    // 36 characters can only be the hyphenated form; uuid rejects bad hyphen
    // placement and non-hex. Uppercase hex is the one thing it accepts that we don't.
    if s.len() != 36 || s.bytes().any(|b| b.is_ascii_uppercase()) {
        return Err(IdParseError);
    }
    Uuid::parse_str(s).map_err(|_| IdParseError)
}

/// Version 4 with the RFC 9562 variant, or nil where the type allows it.
const fn is_valid(bytes: &[u8; 16], nil_allowed: bool) -> bool {
    let v4 = bytes[6] >> 4 == 4 && bytes[8] >> 6 == 0b10;
    v4 || (nil_allowed && u128::from_be_bytes(*bytes) == 0)
}

macro_rules! id_type {
    ($(#[$meta:meta])* $name:ident) => {
        id_type!($(#[$meta])* $name, nil_allowed = false);
    };
    ($(#[$meta:meta])* $name:ident, nil_allowed = $nil:expr) => {
        $(#[$meta])*
        #[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
        pub struct $name(Uuid);

        impl $name {
            /// Parses the 16-byte form (the CBOR representation).
            pub const fn from_bytes(bytes: [u8; 16]) -> Result<Self, IdParseError> {
                if is_valid(&bytes, $nil) {
                    Ok(Self(Uuid::from_bytes(bytes)))
                } else {
                    Err(IdParseError)
                }
            }

            /// The 16-byte form (the CBOR representation).
            pub const fn to_bytes(self) -> [u8; 16] {
                *self.0.as_bytes()
            }

            /// Borrowed 16-byte form.
            pub const fn as_bytes(&self) -> &[u8; 16] {
                self.0.as_bytes()
            }

            /// Fresh random UUIDv4 from the OS CSPRNG.
            #[cfg(feature = "generate")]
            pub fn random() -> Self {
                Self(Uuid::new_v4())
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(&self.0.hyphenated(), f)
            }
        }

        impl fmt::Debug for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(f, concat!(stringify!($name), "({})"), self.0.hyphenated())
            }
        }

        impl FromStr for $name {
            type Err = IdParseError;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                Self::from_bytes(*parse_canonical(s)?.as_bytes())
            }
        }

        impl TryFrom<[u8; 16]> for $name {
            type Error = IdParseError;

            fn try_from(bytes: [u8; 16]) -> Result<Self, Self::Error> {
                Self::from_bytes(bytes)
            }
        }

        impl Serialize for $name {
            fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                serializer.collect_str(self)
            }
        }

        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                struct IdVisitor;

                impl Visitor<'_> for IdVisitor {
                    type Value = $name;

                    fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                        f.write_str("a lowercase canonical UUIDv4 string")
                    }

                    fn visit_str<E: de::Error>(self, v: &str) -> Result<$name, E> {
                        v.parse().map_err(E::custom)
                    }
                }

                deserializer.deserialize_str(IdVisitor)
            }
        }
    };
}

id_type!(
    /// Account identifier.
    UserId
);
id_type!(
    /// Vault identifier, generated by the client that creates the vault.
    VaultId
);
id_type!(
    /// Item identifier, generated by the client. The nil value is reserved
    /// for the vault's metadata record ([`ItemId::VAULT_META`]).
    ItemId,
    nil_allowed = true
);
id_type!(
    /// Registered device.
    DeviceId
);
id_type!(
    /// Attachment blob, reserved by the server (§9).
    BlobId
);
id_type!(
    /// Pairing session (§5.2).
    PairingId
);
id_type!(
    /// Vault invite, generated by the inviter (§7).
    InviteId
);
id_type!(
    /// Single-use login challenge (§4.3).
    ChallengeId
);

impl ItemId {
    /// Nil UUID, the item ID of a vault's `vault_meta` record (§6.1).
    pub const VAULT_META: ItemId = ItemId(Uuid::nil());
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = "3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b34";

    #[test]
    fn json_round_trip() {
        let id: UserId = SAMPLE.parse().unwrap();
        let json = serde_json::to_string(&id).unwrap();
        assert_eq!(json, format!("\"{SAMPLE}\""));
        assert_eq!(serde_json::from_str::<UserId>(&json).unwrap(), id);
        assert_eq!(id.to_string(), SAMPLE);
    }

    #[test]
    fn every_id_type_round_trips() {
        macro_rules! check {
            ($($t:ident),*) => {$(
                let id: $t = SAMPLE.parse().unwrap();
                let json = serde_json::to_string(&id).unwrap();
                assert_eq!(json, format!("\"{SAMPLE}\""));
                assert_eq!(serde_json::from_str::<$t>(&json).unwrap(), id);
                assert_eq!($t::from_bytes(id.to_bytes()).unwrap(), id);
            )*};
        }
        check!(
            UserId,
            VaultId,
            ItemId,
            DeviceId,
            BlobId,
            PairingId,
            InviteId,
            ChallengeId
        );
    }

    #[test]
    fn byte_form_is_big_endian_uuid_order() {
        let id: VaultId = SAMPLE.parse().unwrap();
        let bytes = id.to_bytes();
        assert_eq!(bytes[0], 0x3f);
        assert_eq!(bytes[1], 0x2b);
        assert_eq!(bytes[15], 0x34);
        assert_eq!(id.as_bytes(), &bytes);
        assert_eq!(VaultId::try_from(bytes).unwrap(), id);
    }

    #[test]
    fn vault_meta_is_nil() {
        assert_eq!(ItemId::VAULT_META.to_bytes(), [0; 16]);
        assert_eq!(
            ItemId::VAULT_META.to_string(),
            "00000000-0000-0000-0000-000000000000"
        );
        let parsed: ItemId = "00000000-0000-0000-0000-000000000000".parse().unwrap();
        assert_eq!(parsed, ItemId::VAULT_META);
    }

    #[test]
    fn rejects_non_canonical_text() {
        let bad = [
            "",
            "3F2B8C1E-9D4A-4E7B-8A61-0C5D2F9E7B34", // uppercase
            "3f2b8c1e-9D4a-4e7b-8a61-0c5d2f9e7b34", // mixed case
            "3f2b8c1e9d4a4e7b8a610c5d2f9e7b34",     // simple form
            "{3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b34}",
            "urn:uuid:3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b34",
            " 3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b34",
            "3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b3",   // short
            "3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b345", // long
            "3f2b8c1e-9d4a-4e7b-8a61-0c5d2f9e7b3g",  // not hex
            "3f2b8c1e9-d4a-4e7b-8a61-0c5d2f9e7b34",  // misplaced hyphen
        ];
        for text in bad {
            assert!(text.parse::<UserId>().is_err(), "accepted {text:?}");
            let json = serde_json::to_string(text).unwrap();
            assert!(
                serde_json::from_str::<UserId>(&json).is_err(),
                "accepted {json}"
            );
        }
    }

    #[test]
    fn rejects_other_uuid_versions_and_variants() {
        let bad = [
            "3f2b8c1e-9d4a-1e7b-8a61-0c5d2f9e7b34", // version 1
            "3f2b8c1e-9d4a-7e7b-8a61-0c5d2f9e7b34", // version 7
            "3f2b8c1e-9d4a-4e7b-0a61-0c5d2f9e7b34", // NCS variant
            "3f2b8c1e-9d4a-4e7b-ca61-0c5d2f9e7b34", // Microsoft variant
            "00000000-0000-0000-0000-000000000000", // nil
            "ffffffff-ffff-ffff-ffff-ffffffffffff", // max
        ];
        for text in bad {
            assert!(text.parse::<UserId>().is_err(), "accepted {text:?}");
            let uuid = Uuid::parse_str(text).unwrap();
            assert!(
                UserId::from_bytes(*uuid.as_bytes()).is_err(),
                "accepted bytes of {text:?}"
            );
        }
    }

    #[test]
    fn only_item_ids_allow_nil() {
        let nil = "00000000-0000-0000-0000-000000000000";
        assert_eq!(nil.parse::<ItemId>().unwrap(), ItemId::VAULT_META);
        assert!(nil.parse::<VaultId>().is_err());
        assert!(DeviceId::from_bytes([0; 16]).is_err());
        // Other non-v4 values stay invalid for items too.
        assert!(
            "3f2b8c1e-9d4a-1e7b-8a61-0c5d2f9e7b34"
                .parse::<ItemId>()
                .is_err()
        );
    }

    #[test]
    fn rejects_non_string_json() {
        assert!(serde_json::from_str::<UserId>("42").is_err());
        assert!(serde_json::from_str::<UserId>("null").is_err());
        assert!(serde_json::from_str::<UserId>("[1,2,3]").is_err());
    }

    #[test]
    fn debug_shows_type_and_value() {
        let id: DeviceId = SAMPLE.parse().unwrap();
        assert_eq!(format!("{id:?}"), format!("DeviceId({SAMPLE})"));
    }

    #[cfg(feature = "generate")]
    #[test]
    fn random_ids_are_v4_and_distinct() {
        let a = UserId::random();
        let b = UserId::random();
        assert_ne!(a, b);
        let bytes = a.to_bytes();
        assert_eq!(bytes[6] >> 4, 4, "version nibble");
        assert_eq!(bytes[8] >> 6, 0b10, "variant bits");
        assert_eq!(a.to_string().parse::<UserId>().unwrap(), a);
    }
}
